//! I8c' — the payload of `GSP_SET_SYSTEM_INFO` (`GspSystemInfo`, 928 bytes in
//! r570), built and tested **only in SIMULARE**.
//!
//! This is the first RPC the driver puts in the command queue before ringing
//! GSP-RM's doorbell: where the BARs are in the CPU's physical address space,
//! which PCI device it is, the page size and the user VA limit. Everything we
//! do not know or do not have (ACPI tables, SR-IOV, chipset quirks, display
//! mux) stays **zero**, which in r570 means "absent": `acpiMethodData.bValid`
//! = 0, `totalVFs` = 0, `hypervisorType` = 0 (none), `oorArch` = 0
//! (`OOR_ARCH_X86_64`, `g_gpu_nvoc.h`).
//!
//! Sources (MIT, open-gpu-kernel-modules@570.144, read, re-written):
//! - layout: `gpu/gsp/gsp_static_config.h`; generated by bindgen into
//!   `nvidia_rm570::sysinfo` and every offset below is cross-checked against
//!   it (`tests/rm570_crosscheck.rs`);
//! - which value goes where: `kernel/vgpu/rpc.c` (`rpcGspSetSystemInfo_v17_00`),
//!   `gpu_mgr.c` (`gpumgrSetAttachInfo`: BAR0/BAR1/BAR3, the I/O BAR is not
//!   set on Linux → 0), `osinit.c` (`nv_encode_pci_info` = domain<<32 |
//!   bus<<8 | **slot**), `g_gpu_nvoc.h` (`NVGPU_BUSDEVICE_*` fields),
//!   `kern_gpu_gm107.c` (`PCIDeviceID` = config dword 0 as read,
//!   `PCISubDeviceID` = config dword 0x2C as read, `PCIRevisionID` = dword 8
//!   with the class code masked off), `kernel_bif_gm107.c` + `dev_nv_xve.h`
//!   (`NV_PCFG` mirror = 0x88000..0x88FFF);
//! - nouveau `gsp/r535.c` (MIT) fills the same subset (BAR0/1/3, BDF,
//!   `maxUserVa` = `TASK_SIZE`, the PCFG mirror, ACPI) — agreement noted,
//!   nothing copied.
//!
//! DEDUS (not proven on the board): that GSP-RM 570.144 accepts the zeros
//! for the fields above on a desktop GA104 without ACPI data. NVIDIA's own
//! driver sends real ACPI method results when the platform has them; the
//! workstation's would be absent in our OS. Checked only at the first real
//! boot (the RPC reply's result field), with Adrian present.

use gpu_core::error::{GpuError, GpuResult};

use super::{put_u32, put_u64};

/// `sizeof(GspSystemInfo)` in r570 (x86-64 C layout).
pub const SIZE: usize = 928;

/// NVIDIA's vendor ID; anything else is refused.
pub const NVIDIA_VENDOR: u16 = 0x10de;
/// `DEVICE_BASE(NV_PCFG)` / extent: the PCI config space mirror in BAR0.
pub const PCI_CONFIG_MIRROR_BASE: u32 = 0x0008_8000;
pub const PCI_CONFIG_MIRROR_SIZE: u32 = 0x1000;
/// Linux x86-64 `TASK_SIZE` with 4-level paging (what NVIDIA and nouveau
/// send on Linux). Our OS's user space ends lower; GSP-RM only uses this as
/// an upper bound for user mappings it may be asked about.
pub const MAX_USER_VA_X86_64: u64 = 0x0000_7fff_ffff_f000;
pub const HOST_PAGE_SIZE: u64 = 4096;

/// Byte offsets of the fields we write (r570; cross-checked with bindgen).
pub mod off {
    pub const GPU_PHYS_ADDR: usize = 0;
    pub const GPU_PHYS_FB_ADDR: usize = 8;
    pub const GPU_PHYS_INST_ADDR: usize = 16;
    pub const GPU_PHYS_IO_ADDR: usize = 24;
    pub const NV_DOMAIN_BUS_DEVICE_FUNC: usize = 32;
    pub const MAX_USER_VA: usize = 72;
    pub const PCI_CONFIG_MIRROR_BASE: usize = 80;
    pub const PCI_CONFIG_MIRROR_SIZE: usize = 84;
    pub const PCI_DEVICE_ID: usize = 88;
    pub const PCI_SUB_DEVICE_ID: usize = 92;
    pub const PCI_REVISION_ID: usize = 96;
    pub const OOR_ARCH: usize = 104;
    pub const ACPI_METHOD_DATA: usize = 160;
    pub const HYPERVISOR_TYPE: usize = 836;
    pub const B_IS_PASSTHRU: usize = 840;
    pub const GSP_VF_INFO: usize = 856;
    pub const B_IS_PRIMARY: usize = 896;
    pub const HOST_PAGE_SIZE: usize = 920;
}

/// What the driver knows about the board, from the PCI layer (I0).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct SystemInfoInput {
    /// CPU physical addresses of BAR0 (registers), BAR1 (FB aperture) and
    /// BAR3 (instance memory aperture).
    pub bar0: u64,
    pub bar1: u64,
    pub bar3: u64,
    pub domain: u32,
    pub bus: u8,
    /// PCI device number (0..=31), not devfn.
    pub slot: u8,
    pub vendor: u16,
    pub device: u16,
    pub subsys_vendor: u16,
    pub subsys_device: u16,
    pub revision: u8,
    /// Whether this GPU is the boot display device (VGA decode).
    pub is_primary: bool,
}

/// The few fields the public drivers fill differently (C-108, variants).
/// Everything else in the payload is the same in all four of them.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Options {
    /// `bIsPassthru`: 0 in RM on a desktop, nouveau, nova; **1** in tinygrad.
    pub is_passthru: bool,
    /// `bIsPrimary`: `None` = what the PCI layer says (VGA decode; RM and
    /// nouveau), `Some(v)` = forced (tinygrad and nova send 0).
    pub is_primary: Option<bool>,
    /// `hostPageSize`: 4096 in RM (`osGetPageSize`); **0** (not set) in
    /// nouveau r570, tinygrad and nova.
    pub host_page_size: u64,
}

impl Options {
    /// What we sent up to `os-283`: RM's desktop values.
    pub const OS_283: Options = Options {
        is_passthru: false,
        is_primary: None,
        host_page_size: HOST_PAGE_SIZE,
    };
}

/// `nvDomainBusDeviceFunc` as NVIDIA's `nv_encode_pci_info` builds it.
pub fn encode_domain_bus_slot(domain: u32, bus: u8, slot: u8) -> u64 {
    ((domain as u64) << 32) | ((bus as u64) << 8) | slot as u64
}

/// Builds the 928-byte payload. Refuses inputs that cannot describe a real
/// NVIDIA BAR layout instead of sending GSP-RM something half-filled.
pub fn encode(i: &SystemInfoInput) -> GpuResult<[u8; SIZE]> {
    encode_with(i, &Options::OS_283)
}

/// [`encode`] with the fields a variant (C-108) may set differently.
pub fn encode_with(i: &SystemInfoInput, o: &Options) -> GpuResult<[u8; SIZE]> {
    if i.vendor != NVIDIA_VENDOR {
        return Err(GpuError::InvalidArgument(
            "SET_SYSTEM_INFO: nu e o placa NVIDIA",
        ));
    }
    if i.slot > 31 {
        return Err(GpuError::InvalidArgument(
            "SET_SYSTEM_INFO: numarul dispozitivului PCI > 31",
        ));
    }
    // BAR0 is 16 MiB on every Ampere board and naturally aligned; BAR1/BAR3
    // are at least 4 KiB aligned. Zero means "not assigned" = refuse.
    if i.bar0 == 0 || !i.bar0.is_multiple_of(16 << 20) {
        return Err(GpuError::InvalidArgument(
            "SET_SYSTEM_INFO: BAR0 lipsa sau nealiniat la 16 MiB",
        ));
    }
    for b in [i.bar1, i.bar3] {
        if b == 0 || !b.is_multiple_of(4096) {
            return Err(GpuError::InvalidArgument(
                "SET_SYSTEM_INFO: BAR1/BAR3 lipsa sau nealiniat",
            ));
        }
    }
    let mut b = [0u8; SIZE];
    put_u64(&mut b, off::GPU_PHYS_ADDR, i.bar0);
    put_u64(&mut b, off::GPU_PHYS_FB_ADDR, i.bar1);
    put_u64(&mut b, off::GPU_PHYS_INST_ADDR, i.bar3);
    // GPU_PHYS_IO_ADDR stays 0 (not set by NVIDIA's Linux driver either).
    put_u64(
        &mut b,
        off::NV_DOMAIN_BUS_DEVICE_FUNC,
        encode_domain_bus_slot(i.domain, i.bus, i.slot),
    );
    put_u64(&mut b, off::MAX_USER_VA, MAX_USER_VA_X86_64);
    put_u32(&mut b, off::PCI_CONFIG_MIRROR_BASE, PCI_CONFIG_MIRROR_BASE);
    put_u32(&mut b, off::PCI_CONFIG_MIRROR_SIZE, PCI_CONFIG_MIRROR_SIZE);
    put_u32(
        &mut b,
        off::PCI_DEVICE_ID,
        ((i.device as u32) << 16) | i.vendor as u32,
    );
    put_u32(
        &mut b,
        off::PCI_SUB_DEVICE_ID,
        ((i.subsys_device as u32) << 16) | i.subsys_vendor as u32,
    );
    put_u32(&mut b, off::PCI_REVISION_ID, i.revision as u32);
    b[off::B_IS_PASSTHRU] = o.is_passthru as u8;
    b[off::B_IS_PRIMARY] = o.is_primary.unwrap_or(i.is_primary) as u8;
    put_u64(&mut b, off::HOST_PAGE_SIZE, o.host_page_size);
    Ok(b)
}

#[cfg(test)]
pub(crate) mod tests {
    use super::*;
    use crate::gsp::{get_u32, get_u64};

    /// The workstation's board as Windows reported it (K0). SIMULARE input.
    pub(crate) fn workstation() -> SystemInfoInput {
        use gpu_sim::workstation as w;
        SystemInfoInput {
            bar0: w::BAR0_BASE,
            bar1: w::BAR1_BASE,
            bar3: w::BAR3_BASE,
            domain: 0,
            bus: w::BUS,
            slot: 0,
            vendor: w::VENDOR,
            device: w::DEVICE,
            subsys_vendor: w::SUBSYS_VENDOR,
            subsys_device: w::SUBSYS_DEVICE,
            revision: w::REVISION,
            is_primary: true,
        }
    }

    #[test]
    fn workstation_payload() {
        let b = encode(&workstation()).unwrap();
        assert_eq!(get_u64(&b, off::GPU_PHYS_ADDR), 0xf900_0000);
        assert_eq!(get_u64(&b, off::GPU_PHYS_FB_ADDR), 0xe000_0000);
        assert_eq!(get_u64(&b, off::GPU_PHYS_INST_ADDR), 0xf000_0000);
        assert_eq!(get_u64(&b, off::GPU_PHYS_IO_ADDR), 0);
        assert_eq!(get_u64(&b, off::NV_DOMAIN_BUS_DEVICE_FUNC), 0xb300);
        assert_eq!(get_u32(&b, off::PCI_DEVICE_ID), 0x2482_10de);
        assert_eq!(get_u32(&b, off::PCI_SUB_DEVICE_ID), 0x8813_1043);
        assert_eq!(get_u32(&b, off::PCI_REVISION_ID), 0xa1);
        assert_eq!(get_u32(&b, off::PCI_CONFIG_MIRROR_BASE), 0x88000);
        assert_eq!(get_u32(&b, off::PCI_CONFIG_MIRROR_SIZE), 0x1000);
        assert_eq!(get_u64(&b, off::MAX_USER_VA), 0x7fff_ffff_f000);
        assert_eq!(get_u64(&b, off::HOST_PAGE_SIZE), 4096);
        assert_eq!(b[off::B_IS_PRIMARY], 1);
        // "Absent" = zero: ACPI (bValid + all four method blocks), hypervisor,
        // SR-IOV, OOR arch.
        assert!(
            b[off::ACPI_METHOD_DATA..off::HYPERVISOR_TYPE]
                .iter()
                .all(|&x| x == 0)
        );
        assert_eq!(get_u32(&b, off::HYPERVISOR_TYPE), 0);
        assert!(
            b[off::GSP_VF_INFO..off::B_IS_PRIMARY]
                .iter()
                .all(|&x| x == 0)
        );
        assert_eq!(b[off::OOR_ARCH], 0);
        // Exactly the fields above are non-zero: count the written bytes.
        let written = [
            off::GPU_PHYS_ADDR..off::GPU_PHYS_ADDR + 8,
            off::GPU_PHYS_FB_ADDR..off::GPU_PHYS_FB_ADDR + 8,
            off::GPU_PHYS_INST_ADDR..off::GPU_PHYS_INST_ADDR + 8,
            off::NV_DOMAIN_BUS_DEVICE_FUNC..off::NV_DOMAIN_BUS_DEVICE_FUNC + 8,
            off::MAX_USER_VA..off::PCI_REVISION_ID + 4,
            off::B_IS_PRIMARY..off::B_IS_PRIMARY + 1,
            off::HOST_PAGE_SIZE..SIZE,
        ];
        for (k, &x) in b.iter().enumerate() {
            if x != 0 {
                assert!(written.iter().any(|r| r.contains(&k)), "byte {k} = {x:#x}");
            }
        }
    }

    #[test]
    fn domain_bus_slot_like_nvidia() {
        assert_eq!(encode_domain_bus_slot(0, 0xb3, 0), 0xb300);
        assert_eq!(encode_domain_bus_slot(1, 0x01, 0x1f), 0x1_0000_011f);
    }

    #[test]
    fn bad_inputs_are_refused_not_sent() {
        let ok = workstation();
        let cases = [
            SystemInfoInput {
                vendor: 0x1002,
                ..ok
            },
            SystemInfoInput { slot: 32, ..ok },
            SystemInfoInput { bar0: 0, ..ok },
            SystemInfoInput {
                bar0: 0xf900_1000,
                ..ok
            },
            SystemInfoInput { bar1: 0, ..ok },
            SystemInfoInput {
                bar3: 0xf000_0010,
                ..ok
            },
        ];
        for c in cases {
            assert!(
                matches!(encode(&c), Err(GpuError::InvalidArgument(_))),
                "{c:?}"
            );
        }
    }
}
