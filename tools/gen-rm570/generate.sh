#!/usr/bin/env sh
# Regenerates crates/nvidia-rm570/src/{regs,names,structs,sysinfo,rmapi}.rs from NVIDIA's MIT headers.
# Host-only. Pinned: open-gpu-kernel-modules tag 570.144 (commit below), bindgen-cli 0.71.1.
# Second source (methods C56F/C7C0, QMD V03_00): NVIDIA open-gpu-doc, commit below.
#   tools/gen-rm570/generate.sh <dir-for-the-checkout> <dir-for-open-gpu-doc>
# The checkout is NOT part of this repo; only the generated .rs files are committed.
set -eu
TAG=570.144
COMMIT=8ec351aeb96a93a4bb69ccc12a542bf8a8df2b6f
BINDGEN_VERSION=0.71.1
DOC_COMMIT=9fdf5c4062007929d9f4e6cbad9c9771fe61b880
here="$(cd "$(dirname "$0")" && pwd)"
repo="$here/../.."
src="${1:?usage: generate.sh <checkout-dir> <open-gpu-doc-dir>}"
doc="${2:?usage: generate.sh <checkout-dir> <open-gpu-doc-dir>}"
if [ ! -d "$doc/.git" ]; then
  git clone -q https://github.com/NVIDIA/open-gpu-doc "$doc"
  git -C "$doc" checkout -q "$DOC_COMMIT"
fi
test "$(git -C "$doc" rev-parse HEAD)" = "$DOC_COMMIT" || { echo "open-gpu-doc: wrong commit (want $DOC_COMMIT)"; exit 1; }
if [ ! -d "$src/.git" ]; then
  git clone -q --depth 1 --branch "$TAG" --filter=blob:none --sparse \
    https://github.com/NVIDIA/open-gpu-kernel-modules "$src"
  git -C "$src" sparse-checkout set --no-cone /COPYING \
    /src/common/inc/swref/published/ampere/ga102/ /src/common/inc/swref/published/turing/tu102/ \
    /src/nvidia/arch/nvalloc/common/inc/ /src/common/shared/msgq/inc/msgq/ /src/nvidia/inc/kernel/gpu/gsp/ \
    /src/common/sdk/nvidia/inc/
fi
# I9b: NV_PBUS_BAR0_WINDOW is published only in the Maxwell copy of dev_bus.h.
git -C "$src" sparse-checkout add /src/common/inc/swref/published/maxwell/gm107/
# I9: the full MMU format header (dev_mmu.h with the VER2 entries) ships with UVM.
git -C "$src" sparse-checkout add /kernel-open/nvidia-uvm/hwref/turing/tu102/
# GspSystemInfo (I8c') pulls in RM's kernel headers (NVOC-generated ones included):
# widen the sparse checkout once; still only MIT files from the same commit.
git -C "$src" sparse-checkout add /src/common/inc/ /src/common/nvlink/inband/interface/ \
  /src/nvidia/inc/ /src/nvidia/generated/ /src/nvidia/interface/ /src/nvidia/arch/nvalloc/unix/include/
test "$(git -C "$src" rev-parse HEAD)" = "$COMMIT" || { echo "wrong commit (want $COMMIT)"; exit 1; }
bindgen --version | grep -q " $BINDGEN_VERSION\$" || { echo "need bindgen-cli $BINDGEN_VERSION"; exit 1; }

python3 -I "$here/gen_regs.py" "$src" "$doc" "$repo/crates/nvidia-rm570/src/regs.rs"
# 11 Nov 2026 (after os-279): NV_STATUS codes + RPC function/event names, so the journal can name numbers.
python3 -I "$here/gen_names.py" "$src" "$repo/crates/nvidia-rm570/src/names.rs"

out="$repo/crates/nvidia-rm570/src/structs.rs"
{
  echo "// GENERATED by tools/gen-rm570/generate.sh (bindgen-cli $BINDGEN_VERSION) — do not edit by hand."
  echo "// Source: NVIDIA open-gpu-kernel-modules tag $TAG ($COMMIT): gsp_fw_wpr_meta.h,"
  echo "// msgq_priv.h, gsp_init_args.h, rmgspseq.h, rmRiscvUcode.h. MIT, Copyright NVIDIA CORPORATION & AFFILIATES;"
  echo "// full notice in crates/nvidia-rm570/LICENSE-NVIDIA. The const blocks are bindgen's"
  echo "// compile-time size/offset checks (computed by clang from the C headers)."
  echo "#![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, missing_docs)]"
  echo "#![allow(clippy::all)]"
  echo
  bindgen "$here/wrap.h" --use-core --no-doc-comments --no-debug '.*' \
    --default-macro-constant-type unsigned \
    --allowlist-type 'GspFwWprMeta|msgqTxHeader|msgqRxHeader|GSP_ARGUMENTS_CACHED|MESSAGE_QUEUE_INIT_ARGUMENTS|GSP_SR_INIT_ARGUMENTS|GSP_SEQ_BUF_.*|GSP_SEQUENCER_BUFFER_CMD|RM_RISCV_UCODE_DESC' \
    --allowlist-var 'GSP_FW_WPR_META_.*|MSGQ_.*' \
    -- -I "$src/src/common/sdk/nvidia/inc" -I "$src/src/nvidia/arch/nvalloc/common/inc" \
       -I "$src/src/common/shared/msgq/inc" -I "$src/src/nvidia/inc/kernel" \
       -target x86_64-unknown-linux-gnu
} > "$out"
echo "structs: $(grep -c '^pub struct\|^pub union' "$out") types -> $out"

# I8c': GspSystemInfo (the SET_SYSTEM_INFO payload) from gsp_static_config.h.
# RM's own compile flags (src/nvidia/Makefile) are needed for its headers to parse;
# only the layout comes out (bindgen's compile-time size/offset checks included).
o="$src/src"
sysout="$repo/crates/nvidia-rm570/src/sysinfo.rs"
# Paths have no spaces (scratch checkout); word splitting of $RMFLAGS is intended.
RMFLAGS="-I $o/common/sdk/nvidia/inc -I $o/nvidia/arch/nvalloc/common/inc -I $o/common/shared/msgq/inc -I $o/nvidia/inc/kernel -I $o/nvidia/inc -I $o/nvidia/generated -I $o/nvidia/interface -I $o/common/inc -I $o/nvidia/inc/libraries -I $o/nvidia/arch/nvalloc/unix/include -I $o/nvidia/inc/os -I $o/common/sdk/nvidia/inc/hw -I $o/common/nvlink/inband/interface -I $o/common/inc/swref -D_LANGUAGE_C -D__NO_CTYPE -DNVRM -DLOCK_VAL_ENABLED=0 -DPORT_ATOMIC_64_BIT_SUPPORTED=1 -DPORT_IS_KERNEL_BUILD=1 -DPORT_IS_CHECKED_BUILD=1 -DPORT_MODULE_atomic=1 -DPORT_MODULE_core=1 -DPORT_MODULE_cpu=1 -DPORT_MODULE_crypto=1 -DPORT_MODULE_debug=1 -DPORT_MODULE_memory=1 -DPORT_MODULE_safe=1 -DPORT_MODULE_string=1 -DPORT_MODULE_sync=1 -DPORT_MODULE_thread=1 -DPORT_MODULE_util=1 -DPORT_MODULE_example=0 -DPORT_MODULE_mmio=0 -DPORT_MODULE_time=0 -DRS_STANDALONE=0 -DRS_STANDALONE_TEST=0 -DRS_COMPATABILITY_MODE=1 -DRS_PROVIDES_API_STATE=0 -DNV_CONTAINERS_NO_TEMPLATES -DINCLUDE_NVLINK_LIB -DINCLUDE_NVSWITCH_LIB -DNV_PRINTF_STRINGS_ALLOWED=1 -DNV_ASSERT_FAILED_USES_STRINGS=1 -DPORT_ASSERT_FAILED_USES_STRINGS=1 -include stdarg.h -target x86_64-unknown-linux-gnu"
{
  echo "// GENERATED by tools/gen-rm570/generate.sh (bindgen-cli $BINDGEN_VERSION) — do not edit by hand."
  echo "// Source: NVIDIA open-gpu-kernel-modules tag $TAG ($COMMIT): gsp_static_config.h"
  echo "// (GspSystemInfo + the types it embeds). MIT, Copyright NVIDIA CORPORATION & AFFILIATES;"
  echo "// full notice in crates/nvidia-rm570/LICENSE-NVIDIA. Layout only; no code."
  echo "#![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, missing_docs)]"
  echo "#![allow(clippy::all)]"
  echo
  # shellcheck disable=SC2086
  bindgen "$here/wrap_sysinfo.h" --use-core --no-doc-comments --no-debug '.*' \
    --default-macro-constant-type unsigned --allowlist-type 'GspSystemInfo' \
    -- $RMFLAGS
} > "$sysout"
echo "sysinfo: $(grep -c '^pub struct' "$sysout") types -> $sysout"
# I8e ("golden image"): RM API allocation/control parameters + the RPC wrappers.
rmout="$repo/crates/nvidia-rm570/src/rmapi.rs"
{
  echo "// GENERATED by tools/gen-rm570/generate.sh (bindgen-cli $BINDGEN_VERSION) — do not edit by hand."
  echo "// Source: NVIDIA open-gpu-kernel-modules tag $TAG ($COMMIT): nvos.h, class/cl0000.h, cl0080.h,"
  echo "// cl2080.h, cl90f1.h, clc56f.h, clc7c0.h, clc7b5.h, cla06c.h, cl9067.h, cl2080_notification.h,"
  echo "// alloc/alloc_channel.h, ctrl0080fifo.h,"
  echo "// ctrl0080dma.h, ctrl2080fifo.h, ctrl2080gpu.h, ctrl2080internal.h, ctrl90f1.h, ctrla06c.h, ctrla06fgpfifo.h, ctrlc36f.h, g_rpc-structures.h,"
  echo "// g_sdk-structures.h."
  echo "// MIT, Copyright NVIDIA CORPORATION & AFFILIATES; full notice in crates/nvidia-rm570/LICENSE-NVIDIA."
  echo "// Layout only; no code."
  echo "#![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, missing_docs)]"
  echo "#![allow(clippy::all)]"
  echo
  # shellcheck disable=SC2086
  bindgen "$here/wrap_rmapi.h" --use-core --no-doc-comments --no-debug '.*' \
    --default-macro-constant-type unsigned \
    --allowlist-type 'NV0000_ALLOC_PARAMETERS|NV0080_ALLOC_PARAMETERS|NV2080_ALLOC_PARAMETERS|NV_VASPACE_ALLOCATION_PARAMETERS|NV_CHANNEL_ALLOC_PARAMS|NV_MEMORY_DESC_PARAMS|NV2080_CTRL_FIFO_GET_DEVICE_INFO_TABLE_PARAMS|NV90F1_CTRL_VASPACE_COPY_SERVER_RESERVED_PDES_PARAMS|NV2080_CTRL_INTERNAL_STATIC_KGR_GET_CONTEXT_BUFFERS_INFO_PARAMS|NV2080_CTRL_GPU_PROMOTE_CTX_PARAMS|rpc_set_page_directory_v1E_05|NV_CHANNEL_GROUP_ALLOCATION_PARAMETERS|NV_CTXSHARE_ALLOCATION_PARAMETERS|NVA06F_CTRL_GPFIFO_SCHEDULE_PARAMS|NVC36F_CTRL_CMD_GPFIFO_GET_WORK_SUBMIT_TOKEN_PARAMS|Nvc56fControl_struct|AmpereAControlGPFifo|NV2080_CTRL_INTERNAL_STATIC_GR_GET_INFO_PARAMS' \
    --allowlist-var 'RPC_GSP_RM_.*|NV01_ROOT|NV01_DEVICE_0|NV20_SUBDEVICE_0|FERMI_VASPACE_A|AMPERE_CHANNEL_GPFIFO_A|AMPERE_COMPUTE_B|AMPERE_DMA_COPY_B|NV2080_CTRL_CMD_GPU_PROMOTE_CTX|NV2080_CTRL_CMD_FIFO_GET_DEVICE_INFO_TABLE|NV90F1_CTRL_CMD_VASPACE_COPY_SERVER_RESERVED_PDES|NV2080_CTRL_CMD_INTERNAL_STATIC_KGR_GET_CONTEXT_BUFFERS_INFO|NV0080_CTRL_FIFO_GET_ENGINE_CONTEXT_PROPERTIES_ENGINE_ID_.*|NV2080_CTRL_FIFO_GET_DEVICE_INFO_TABLE_.*|NV2080_CTRL_FIFO_DEVICE_INFO_ENGINE_DATA_TYPE_.*|NV2080_ENGINE_TYPE_GR0|NV2080_ENGINE_TYPE_COPY0|NV2080_CTRL_GPU_PROMOTE_CTX_.*|NV2080_CTRL_GPU_PROMOTE_CONTEXT_MAX_ENTRIES|NV_MAX_SUBDEVICES|NV90F1_CTRL_VASPACE_COPY_SERVER_RESERVED_PDES_.*|GMMU_FMT_MAX_LEVELS|NV0080_CTRL_CMD_DMA_SET_PAGE_DIRECTORY|NV0080_CTRL_DMA_SET_PAGE_DIRECTORY_FLAGS_.*|NV_DEVICE_ALLOCATION_VAMODE_.*|KEPLER_CHANNEL_GROUP_A|FERMI_CONTEXT_SHARE_A|NV2080_ENGINE_TYPE_GRAPHICS|NV_CTXSHARE_ALLOCATION_FLAGS_SUBCONTEXT_.*|NVA06C_CTRL_CMD_GPFIFO_SCHEDULE|NVC36F_CTRL_CMD_GPFIFO_GET_WORK_SUBMIT_TOKEN|NV2080_CTRL_CMD_INTERNAL_STATIC_KGR_GET_INFO|NV2080_CTRL_INTERNAL_GR_MAX_ENGINES|NV0080_CTRL_GR_INFO_MAX_SIZE|NV0080_CTRL_GR_INFO_INDEX_SM_VERSION|NV0080_CTRL_GR_INFO_INDEX_MAX_WARPS_PER_SM|NV0080_CTRL_GR_INFO_INDEX_LITTER_NUM_GPCS|NV0080_CTRL_GR_INFO_INDEX_LITTER_NUM_TPC_PER_GPC|NV0080_CTRL_GR_INFO_INDEX_LITTER_NUM_SM_PER_TPC' \
    -- $RMFLAGS
} > "$rmout"
echo "rmapi: $(grep -c '^pub struct\|^pub union' "$rmout") types -> $rmout"
rustfmt --edition 2024 "$repo/crates/nvidia-rm570/src/regs.rs" "$repo/crates/nvidia-rm570/src/names.rs" "$out" "$sysout" "$rmout"
