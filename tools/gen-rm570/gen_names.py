#!/usr/bin/env python3
"""Generate the NV_STATUS and RPC function/event name tables from NVIDIA's MIT headers.

Host-only tool (continuation of C-20 B, after the board test of 11 Nov 2026:
the journal showed `rpc_result = 0x59` and 843 messages with function 0x1020
and the driver could name neither). Reads, from a checkout of NVIDIA
open-gpu-kernel-modules at tag 570.144:
  * src/common/sdk/nvidia/inc/nvstatuscodes.h    -> NV_STATUS_CODE(NAME, 0x.., "text")
  * src/nvidia/inc/kernel/vgpu/rpc_global_enums.h -> X(UNIT, NAME, n) / E(NAME, 0x..)
and writes `crates/nvidia-rm570/src/names.rs`: three sorted tables of
(number, name[, description]). Standard library only; data only.

Usage: gen_names.py <ogkm-checkout> <output.rs>
"""
import re
import sys

STATUS = "src/common/sdk/nvidia/inc/nvstatuscodes.h"
ENUMS = "src/nvidia/inc/kernel/vgpu/rpc_global_enums.h"

RE_STATUS = re.compile(r'^\s*NV_STATUS_CODE\(\s*(\w+)\s*,\s*(0x[0-9A-Fa-f]+|\d+)\s*,\s*"([^"]*)"\s*\)')
RE_FUNC = re.compile(r'^\s*X\(\s*\w+\s*,\s*(\w+)\s*,\s*(0x[0-9A-Fa-f]+|\d+)\s*\)')
RE_EVENT = re.compile(r'^\s*E\(\s*(\w+)\s*,\s*(0x[0-9A-Fa-f]+|\d+)\s*\)')


def read(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        return f.read().splitlines()


def main(src, out):
    status, funcs, events = [], [], []
    for line in read(f"{src}/{STATUS}"):
        m = RE_STATUS.match(line)
        if m:
            status.append((int(m.group(2), 0), m.group(1), m.group(3)))
    for line in read(f"{src}/{ENUMS}"):
        m = RE_FUNC.match(line)
        if m:
            funcs.append((int(m.group(2), 0), m.group(1)))
            continue
        m = RE_EVENT.match(line)
        if m:
            events.append((int(m.group(2), 0), m.group(1)))
    if not status or not funcs or not events:
        sys.exit("gen_names.py: a table came out empty — header format changed?")
    for name, table in (("status", status), ("funcs", funcs), ("events", events)):
        nums = [t[0] for t in table]
        if len(set(nums)) != len(nums):
            sys.exit(f"gen_names.py: duplicate numbers in {name}")
    status.sort()
    funcs.sort()
    events.sort()
    with open(out, "w", encoding="utf-8") as f:
        w = f.write
        w("// GENERATED by tools/gen-rm570/generate.sh (gen_names.py) — do not edit by hand.\n")
        w("// Source: NVIDIA open-gpu-kernel-modules tag 570.144: nvstatuscodes.h, rpc_global_enums.h.\n")
        w("// MIT, Copyright NVIDIA CORPORATION & AFFILIATES; full notice in crates/nvidia-rm570/LICENSE-NVIDIA.\n")
        w("// Names only (what a number means in the board's journal); no code.\n\n")
        w("/// `NV_STATUS` codes: (code, name, NVIDIA's one-line description), sorted by code.\n")
        w(f"pub const NV_STATUS: &[(u32, &str, &str)] = &[\n")
        for code, name, text in status:
            text = text.replace("\\", "\\\\").replace('"', '\\"')
            w(f'    ({code:#010x}, "{name}", "{text}"),\n')
        w("];\n\n")
        w("/// RPC functions the CPU sends (`NV_VGPU_MSG_FUNCTION_*`): (number, name), sorted.\n")
        w("pub const RPC_FUNCTIONS: &[(u32, &str)] = &[\n")
        for num, name in funcs:
            w(f'    ({num}, "{name}"),\n')
        w("];\n\n")
        w("/// Events GSP-RM sends on its own (`NV_VGPU_MSG_EVENT_*`): (number, name), sorted.\n")
        w("pub const RPC_EVENTS: &[(u32, &str)] = &[\n")
        for num, name in events:
            w(f'    ({num:#06x}, "{name}"),\n')
        w("];\n")
    print(f"names: {len(status)} status codes, {len(funcs)} functions, {len(events)} events -> {out}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
